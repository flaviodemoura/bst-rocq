#!/usr/bin/env python3
"""Map every Rocq definition to its line in the source file.

Reads the .glob files produced by `rocq compile` and writes a LaTeX file of
\\coqsrcline{<key>}{<file.v>}{<line>} entries, which
paa-2026-2-projeto-enunciado.tex uses to link to the repository. Each definition gets two keys: the one coqdoc uses
(BST.bst.insert BST) and its plain name (bst.insert_BST).

Usage: glob2links.py <src dir> <logical prefix> <module>... > out.tex
"""
import sys
from pathlib import Path

SKIP_KINDS = {"binder", "not"}  # bound variables and notations: no useful target


def entries(src: Path, prefix: str, module: str):
    source = (src / f"{module}.v").read_bytes()
    for line in (src / f"{module}.glob").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) != 4 or parts[0] in SKIP_KINDS or ":" not in parts[1]:
            continue
        kind, span, secpath, name = parts
        start = int(span.split(":")[0])  # byte offset into the .v file
        lineno = source.count(b"\n", 0, start) + 1
        path = [module] + ([] if secpath == "<>" else [secpath]) + [name]
        # coqdoc's LaTeX backend writes underscores in keys as spaces
        yield ".".join([prefix] + path).replace("_", " "), f"{module}.v", lineno
        # the plain name, e.g. bst.insert_BST
        yield ".".join(path), f"{module}.v", lineno


def main():
    src, prefix, modules = Path(sys.argv[1]), sys.argv[2], sys.argv[3:]
    print("% Generated by tools/glob2links.py -- do not edit")
    for module in modules:
        for key, file, lineno in entries(src, prefix, module):
            print(f"\\coqsrcline{{{key}}}{{{file}}}{{{lineno}}}")


if __name__ == "__main__":
    main()
